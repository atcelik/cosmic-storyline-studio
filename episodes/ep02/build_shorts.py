"""Builds two vertical Shorts (1080x1920) from approved EP02 lines and scenes.
  ep02_short1: the race to the Sun (light vs spacecraft, jet, car, walker + light-trip counter)
  ep02_short2: what if the Sun switched off this very second
Scenes are the same scale2d specs, re-fitted to a 9:16 frame (spec["size"]); narration reuses EP02 lines only.
Run on the machine that has the EP02 textures: python episodes/ep02/build_shorts.py"""
import copy, json, shutil, subprocess
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent
W, H = 1080, 1920
SPEED = 1.2        # Shorts want a punchier delivery than the recorded storyteller pace (pitch is kept)
EP = json.loads((HERE / "episode.json").read_text())
BY_ID = {s["id"]: s for s in EP["shots"]}

SHORTS = {
    "ep02_short1": dict(
        title="Light vs a jet, a car and a human: the race to the Sun #shorts",
        question="How long would different things take to reach the Sun, compared with light?",
        ids=["S150", "S151", "S152", "S153", "S154"],
        voice="short1.wav", cuts=[[0.0, 7.28], [7.28, 12.45], [12.45, 18.77], [18.77, 28.26], [28.26, 33.28]],
        card=("Race to the Sun", "Light vs everything"),
        end="Full video on the channel"),
    "ep02_short2": dict(
        title="What if the Sun switched off right now? #shorts",
        question="What would we notice if the Sun switched off this very second?",
        ids=["S001", "S043", "S044", "S046", "S084"],
        voice="short2.wav", cuts=[[0.0, 6.42], [6.42, 10.97], [10.97, 14.43], [14.43, 19.75], [19.75, 26.65]],
        card=("The Sun", "Eight minutes late"),
        end="Full video on the channel"),
}


def vertical(spec, sid):
    spec["size"] = [W, H]
    if spec.get("race"):
        r = spec["race"]
        r["x_km"] = [230, 870]                    # keep the icons inside the narrow frame
        for ln in r["lanes"]:
            if ln.get("shuttle"):
                ln["name"] = ""                   # the "LIGHT TRIPS" counter says it already
            ln["name"] = ln["name"].replace("FASTEST SPACECRAFT EVER BUILT", "FASTEST SPACECRAFT")
            ln["y_frac"] = round(0.19 + (ln["y_frac"] - 0.24) * 0.72, 3)     # keep the bottom third free for captions
            ln["icon_size"] = 0.04 if ln.get("icon") == "light" else round(ln.get("icon_size", 0.04) * 1.25, 3)
    for b in spec.get("bodies", []):              # bigger bodies: the horizontal Sun-Earth line is narrow on a phone
        if b.get("name") == "EARTH":
            b["diameter_km"] = b["diameter_km"] * 3
        if b.get("name") == "THE SUN":
            b["diameter_km"] = b["diameter_km"] * 1.5
    return spec


def main():
    for name, cfg in SHORTS.items():
        out = ROOT / name
        if out.exists():
            shutil.rmtree(out)
        (out / "assets" / "space3d").mkdir(parents=True)
        (out / "assets" / "music").mkdir()
        shutil.copy(HERE / "music" / "drone.wav", out / "assets" / "music" / "drone.wav")
        if (HERE / "sprites").exists():
            shutil.copytree(HERE / "sprites", out / "sprites")
        for tex in ("EARTH2.jpg", "MOON2.jpg", "SUN2.jpg"):
            src = HERE / "assets" / tex
            if src.exists():
                shutil.copy(src, out / "assets" / tex)
        (out / "voice").mkdir()
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(HERE / "shorts_voice" / cfg["voice"]), "-filter:a", f"atempo={SPEED}",
                        "-ac", "1", "-ar", "24000", str(out / "voice" / "voice.wav")], check=True)
        cuts = [[round(a / SPEED, 3), round(b / SPEED, 3)] for a, b in cfg["cuts"]]
        shots = []
        for i, sid in enumerate(cfg["ids"]):
            s = copy.deepcopy(BY_ID[sid])
            s["beat"] = "B1"
            s.pop("chapter", None)
            s["transition_out"] = {"type": "cut"}
            s.pop("label", None)
            s["min_duration"] = 3.5
            spec = json.loads((HERE / "assets" / "space3d" / f"{sid}.json").read_text())
            spec = vertical(spec, sid)
            spec["fit"] = True
            (out / "assets" / "space3d" / f"{sid}.json").write_text(json.dumps(spec, indent=1))
            shots.append(s)
        shots[0]["vo_lead"] = 0.3
        shots[-1]["min_duration"] = 5.0
        ep = {"schema_version": 2,
              "episode": {"id": name, "title": cfg["title"], "language": "en", "central_question": cfg["question"]},
              "format": {"width": W, "height": H},
              "burn_captions": True, "caption_words": 3,
              "voice": {"engine": "file", "file": "voice/voice.wav", "cuts": cuts}, "music": {"file": "assets/music/drone.wav", "credit": "Procedurally generated by us",
                                               "license": "own work", "gain_db": -15},
              "beats": [{"id": "B1", "name": "Short"}], "shots": shots}
        (out / "episode.json").write_text(json.dumps(ep, indent=2, ensure_ascii=False) + "\n")
        print(name, len(shots), "shots ->", out)


if __name__ == "__main__":
    main()
